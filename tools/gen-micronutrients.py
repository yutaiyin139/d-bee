# 特殊：腌制/加工类名称片段 → 强制高钠（覆盖默认）
SALTY_HINT = ['腌', '卤', '酱', '腊', '熏', '榨菜', '咸', '腐乳', '梅干菜', '雪里蕻', '酸菜', '泡菜']
# 甜味/含糖类名称片段 → 强制较高添加糖
SWEET_HINT = ['糖', '甜', '蜜', '果脯', '果酱', '糖水', '炼乳', '巧克力', '蜂蜜', '月饼', '沙琪玛', '蜜饯']


def normalize(name: str) -> str:
    """去掉括号别名，取主名做精确匹配 key"""
    return name.split('（')[0].split('(')[0].strip()


def lookup(name: str, category: str):
    """返回 (sodium, fiber, added_sugar)。优先精确匹配，否则分类默认 + 关键词修正"""
    key = name
    if key in NUTRI:
        return NUTRI[key]

    base = normalize(name)
    if base in NUTRI:
        return NUTRI[base]

    # 兜底：分类默认值
    na, fb, sugar = CATEGORY_DEFAULT.get(category, (200, 1.0, 1.0))

    # 关键词修正
    if any(h in name for h in SALTY_HINT):
        na = max(na, 500)
    if any(h in name for h in SWEET_HINT):
        sugar = max(sugar, 8.0)

    return (na, fb, sugar)


def main():
    files = ['foodsDataCore.ts', 'foodsDataFresh.ts', 'foodsDataDishes.ts']
    total = 0
    exact = 0
    missing_names = []

    for fn in files:
        path = os.path.join(SRC, fn)
        with open(path, 'r', encoding='utf-8') as f:
            lines = f.read().split('\n')

        out_lines = []
        category = '其他'
        for line in lines:
            t = line.strip()
            if t.startswith('#'):
                category = t[1:].strip()
                # 更新文件头注释里的格式说明
                out_lines.append(line)
                continue
            # 跳过注释行（/* */ 或 // 或 * 开头），避免污染文件头
            if t.startswith('*') or t.startswith('//') or t.startswith('/*'):
                out_lines.append(line)
                continue
            if '|' not in t:
                out_lines.append(line)
                continue

            parts = line.split('|')
            # 只有 7 列且非空的数据行才处理（排除表头注释）
            if len(parts) < 7:
                out_lines.append(line)
                continue

            name = parts[0].strip()
            # 跳过可能的表头行
            if name in ('名称', '食物名称'):
                out_lines.append(line)
                continue

            na, fb, sugar = lookup(name, category)
            if name in NUTRI or normalize(name) in NUTRI:
                exact += 1
            else:
                missing_names.append((category, name))

            # 追加三列（注意：原 line 可能带 \r，用 strip 后重建更安全）
            new_line = line.rstrip('\r\n') + f'|{na}|{fb}|{sugar}'
            out_lines.append(new_line)
            total += 1

        with open(path, 'w', encoding='utf-8') as f:
            f.write('\n'.join(out_lines))

    print(f'总条目: {total}')
    print(f'精确命中: {exact}')
    print(f'分类默认兜底: {total - exact}')
    print(f'\n--- 兜底条目（未精确命中，用分类默认）共 {len(missing_names)} 条 ---')
    from collections import Counter
    by_cat = Counter(c for c, _ in missing_names)
    for c, n in by_cat.most_common():
        print(f'  {c}: {n} 条')


if __name__ == '__main__':
    main()
